/**
 * Глоссарий.
 *
 * Redis — внешнее хранилище состояний звонков, лимитов и очереди OTP.
 * Клиент ioredis, по одному соединению на роль.
 * BLPOP — блокирующая команда Redis: ждёт появления элемента в списке и забирает его. Соединение занято, пока команда не вернётся.
 * Роль — назначение соединения. В этом файле две роли: общий клиент для обычных команд и отдельный клиент для BLPOP.
 */

import Redis from "ioredis";
import { env } from "../../config";

/**
 * createRedis — возвращает клиент Redis с параметрами из конфигурации.
 */
function createRedis() {
  return new Redis({
    host: env.redisHost,
    port: env.redisPort,
    password: env.redisPassword,
  });
}

/**
 * redisClient — представляет общий клиент Redis для HTTP-обработчиков, воркеров и хранилищ.
 * Блокирующие команды через него не идут.
 * Этот файл — исключение из правила «никаких объектов-синглтонов».
 * Два клиента создаются один раз на процесс намеренно. Каждый владеет своим соединением.
 */
export const redisClient = createRedis();

/**
 * redisBlockingClient — представляет отдельный клиент Redis для BLPOP в воркере очереди OTP.
 * Блокирующая команда занимает соединение, пока не вернётся, поэтому общий клиент для маршрутов аутентификации не подходит.
 * Иначе каждый BLPOP задерживал бы эти запросы.
 */
export const redisBlockingClient = createRedis();
